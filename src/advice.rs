//! Человеческое объяснение: почему случился фриз и что делать.
//! Здесь нет догадок про конкретную игру: каждый совет привязан к тому, что реально измерено.
//! Если данных не хватает, текст так и говорит («возможные причины»), а не выдаёт предположение за факт.

use crate::model::{Cause, Incident, Sample};

pub struct Advice {
    pub title: String,
    /// Почему это вызывает фриз (подробно)
    pub why: String,
    /// Что сделать, по убыванию пользы
    pub fixes: Vec<String>,
    /// Насколько этот вывод важен при сортировке итогов
    pub weight: u32,
    /// Тип причины для группировки одинаковых выводов
    pub kind: &'static str,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Severity {
    Minor,
    Noticeable,
    Heavy,
}

impl Severity {
    pub fn label(self) -> &'static str {
        match self {
            Severity::Minor => "лёгкий",
            Severity::Noticeable => "заметный",
            Severity::Heavy => "сильный",
        }
    }
}

/// Сколько кадров при 60 FPS «потерялось» за время зависания.
pub fn frames_lost(ms: u32) -> u32 {
    ((ms as f32) / 16.7).round() as u32
}

pub fn severity(inc: &Incident) -> Severity {
    if inc.peak_stall_ms >= 250 {
        Severity::Heavy
    } else if inc.peak_stall_ms >= 100 || inc.end_ms - inc.start_ms >= 10_000 {
        Severity::Noticeable
    } else {
        Severity::Minor
    }
}

