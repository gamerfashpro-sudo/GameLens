mod tests {
    use super::*;

    fn inc(peak: u32, causes: Vec<Cause>) -> Incident {
        Incident { start_ms: 0, end_ms: 1000, peak_stall_ms: peak, causes }
    }

    #[test]
    fn every_cause_has_explanation_and_fixes() {
        let all = vec![
            Cause::HeavyProcess { name: "MsMpEng.exe".into(), cpu: 40.0 },
            Cause::HeavyProcess { name: "unknown.exe".into(), cpu: 40.0 },
            Cause::SingleThreadBound { core_pct: 100, total_pct: 30.0 },
            Cause::CpuSaturated { total_pct: 99.0 },
            Cause::MemoryPressure { used_pct: 95.0, swap_mb: 2000 },
            Cause::UnexplainedStall { stall_ms: 300 },
            Cause::GpuBound { gpu_pct: 99.0 },
            Cause::DiskSlow { lat_ms: 80.0, busy_pct: 100.0 },
            Cause::DriverLatency { dpc_pct: 20.0 },
            Cause::CpuThrottle { freq_pct: 50.0 },
            Cause::HardPageFaults { pages_per_s: 900.0 },
        ];
        for c in all {
            let a = advise(&c);
            assert!(a.why.len() > 60, "слишком короткое объяснение: {}", a.title);
            assert!(a.fixes.len() >= 3, "мало советов: {}", a.title);
        }
    }

    #[test]
    fn known_process_gets_specific_tip() {
        let a = advise(&Cause::HeavyProcess { name: "MsMpEng.exe".into(), cpu: 30.0 });
        assert!(a.why.contains("Defender"));
        assert!(a.fixes[0].contains("исключения"));
    }

    #[test]
    fn severity_and_frames() {
        assert!(severity(&inc(300, vec![])) == Severity::Heavy);
        assert!(severity(&inc(60, vec![])) == Severity::Minor);
        assert_eq!(frames_lost(167), 10);
    }

    #[test]
    fn score_drops_with_incidents() {
        let s = summarize(&[], &[]);
        assert_eq!(s.score, 100);
        let s = summarize(&[], &[inc(500, vec![]), inc(500, vec![])]);
        assert!(s.score < 90);
    }

    #[test]
    fn findings_are_grouped_by_kind() {
        let i = vec![
            inc(100, vec![Cause::MemoryPressure { used_pct: 95.0, swap_mb: 1 }]),
            inc(100, vec![Cause::MemoryPressure { used_pct: 96.0, swap_mb: 1 }, Cause::GpuBound { gpu_pct: 99.0 }]),
        ];
        let f = top_findings(&i);
        assert_eq!(f.len(), 2);
        assert_eq!(f[0].0.kind, "memory");
        assert_eq!(f[0].1, 2);
    }
}
