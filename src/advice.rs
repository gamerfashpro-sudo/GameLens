/// Итог по всей записи
pub struct Summary {
    pub score: u32,
    pub verdict: &'static str,
    pub avg_cpu: f32,
    pub peak_mem_pct: f32,
    pub worst_stall_ms: u32,
    #[allow(dead_code)]
    pub stall_count: usize,
}

pub fn summarize(samples: &[Sample], incidents: &[Incident]) -> Summary {
    let n = samples.len().max(1) as f32;
    let avg_cpu = samples.iter().map(|s| s.cpu_total).sum::<f32>() / n;
    let peak_mem_pct = samples.iter().map(|s| s.mem_pct()).fold(0.0, f32::max);
    let worst = samples.iter().map(|s| s.stall_ms).max().unwrap_or(0);
    let stall_count = samples.iter().filter(|s| s.stall_ms >= 50).count();
    let mut penalty = 0u32;
    for i in incidents {
        penalty += 5 + (i.peak_stall_ms / 50).min(10) * 2;
    }
    let score = 100u32.saturating_sub(penalty);
    let verdict = match score {
        90..=100 => "Отлично: серьёзных проблем не найдено",
        70..=89 => "Нормально, но есть замечания",
        40..=69 => "Заметные проблемы с плавностью",
        _ => "Серьёзные проблемы с плавностью",
    };
    Summary { score, verdict, avg_cpu, peak_mem_pct, worst_stall_ms: worst, stall_count }
}

/// Главные выводы по всей записи: причины, сгруппированные по типу, самые важные первыми.
pub fn top_findings(incidents: &[Incident]) -> Vec<(Advice, usize)> {
    use std::collections::HashMap;
    let mut by_kind: HashMap<&'static str, (Advice, usize, u32)> = HashMap::new();
    for inc in incidents {
        for c in &inc.causes {
            let a = advise(c);
            let kind = a.kind;
            let entry = by_kind.entry(kind).or_insert((a, 0, 0));
            entry.1 += 1;
            entry.2 = entry.2.max(inc.peak_stall_ms);
        }
    }
    let mut v: Vec<(Advice, usize, u32)> = by_kind.into_values().collect();
    v.sort_by(|a, b| (b.1 as u32 * 10 + b.0.weight + b.2 / 20).cmp(&(a.1 as u32 * 10 + a.0.weight + a.2 / 20)));
    v.into_iter().map(|(a, n, _)| (a, n)).collect()
}

